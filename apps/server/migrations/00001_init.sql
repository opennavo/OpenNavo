-- ========== Content operations ==========
CREATE TABLE collections (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug           TEXT NOT NULL UNIQUE,
  status         TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','published','archived')),
  publish_at     TIMESTAMPTZ,
  unpublish_at   TIMESTAMPTZ,
  sort           INTEGER NOT NULL DEFAULT 0,
  cover_asset_id BIGINT REFERENCES assets(id) ON DELETE SET NULL,
  created_by     BIGINT REFERENCES admin_users(id),
  updated_by     BIGINT REFERENCES admin_users(id),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE collection_i18n (
  collection_id BIGINT NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
  locale        TEXT NOT NULL CHECK (locale IN ('zh-CN','en-US')),
  title         TEXT NOT NULL,
  subtitle      TEXT,
  body          TEXT,                                  -- Markdown
  PRIMARY KEY (collection_id, locale)
);

CREATE TABLE collection_items (
  collection_id BIGINT NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
  package_id    BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  sort          INTEGER NOT NULL DEFAULT 0,
  note_zh       TEXT,
  note_en       TEXT,
  PRIMARY KEY (collection_id, package_id)
);

CREATE TABLE features (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placement     TEXT NOT NULL CHECK (placement IN ('home_hero','home_secondary','category_top')),
  category_id   BIGINT REFERENCES categories(id) ON DELETE CASCADE,
  target_type   TEXT NOT NULL CHECK (target_type IN ('package','collection','url')),
  package_id    BIGINT REFERENCES packages(id) ON DELETE CASCADE,
  collection_id BIGINT REFERENCES collections(id) ON DELETE CASCADE,
  url           TEXT,
  glow_color    TEXT,                                  -- Hero glow color; empty uses brand purple #5B5BD6
  status        TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','published','archived')),
  starts_at     TIMESTAMPTZ,
  ends_at       TIMESTAMPTZ,
  sort          INTEGER NOT NULL DEFAULT 0,
  created_by    BIGINT REFERENCES admin_users(id),
  updated_by    BIGINT REFERENCES admin_users(id),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (placement <> 'category_top' OR category_id IS NOT NULL),
  CHECK ((target_type = 'package'    AND package_id IS NOT NULL)
      OR (target_type = 'collection' AND collection_id IS NOT NULL)
      OR (target_type = 'url'        AND url IS NOT NULL))
);

CREATE TABLE feature_i18n (
  feature_id BIGINT NOT NULL REFERENCES features(id) ON DELETE CASCADE,
  locale     TEXT NOT NULL CHECK (locale IN ('zh-CN','en-US')),
  badge      TEXT,                                     -- "Featured this week"
  title      TEXT NOT NULL,                            -- 「Ghostty 1.3」
  subtitle   TEXT,                                     -- Second-line accent text, for example "A terminal that feels this fast."
  body       TEXT,                                     -- Only **bold** markup is allowed for highlighting
  cta_label  TEXT,
  PRIMARY KEY (feature_id, locale)
);

